import { test, expect, type Page } from '@playwright/test'
import path from 'node:path'
const shots = path.resolve('./output/agent-real-writes-20260918/shots')
async function login(page: Page, account: string, password: string, route: RegExp) {
  await page.goto('/login', { waitUntil: 'domcontentloaded' })
  await page.fill("input[placeholder='请输入账号']", account)
  await page.fill("input[placeholder='请输入密码']", password)
  await page.getByRole('button', { name: /登\s*录/ }).first().click()
  await page.waitForURL(route, { timeout: 45000 })
}
async function openSidebar(page: Page) {
  const entry = page.getByRole('button', { name: 'AI 助手' })
  await expect(entry).toBeVisible({ timeout: 30000 })
  await entry.click()
  await expect(page.locator('#agent-input')).toBeVisible({ timeout: 20000 })
}
test('teacher auto task: preview creates nothing, confirm creates paused only', async ({ page }) => {
  const posts: string[] = []
  page.on('request', r => {
    const u = new URL(r.url())
    if (u.pathname.indexOf('/api/') === 0) posts.push(r.method() + ' ' + u.pathname)
  })
  await login(page, 't003', process.env.E2E_PW_TEACHER || '123456', /\/teacher\//)
  await openSidebar(page)
  await page.getByRole('tab', { name: '自动化任务' }).click()
  const composer = page.locator('#agent-input')
  await composer.fill('鉴定截止前两天站内提醒未提交心得的同学')
  await composer.press('Enter')
  const flow = page.locator('article.auto-flow')
  await expect(flow).toBeVisible({ timeout: 60000 })
  await expect(flow).toContainText('鉴定截止前提醒未交心得', { timeout: 60000 })
  const createBtn = flow.getByRole('button', { name: '确认创建（默认暂停）' })
  await expect(createBtn).toBeEnabled({ timeout: 30000 })
  await expect(flow).not.toContainText('已创建：', { timeout: 5000 }).catch(() => {})
  await createBtn.click()
  await expect(flow).toContainText('已创建：', { timeout: 60000 })
  await expect(flow).toContainText('默认暂停', { timeout: 30000 })
  const text = await flow.innerText()
  const m = text.match(/#(\d+)/)
  console.log('AUTOTASK_CREATED id=' + (m ? m[1] : 'unknown'))
  console.log('AUTOTASK_POSTS=' + JSON.stringify(posts.filter(u => u.indexOf('auto-task') >= 0 || u.indexOf('auto_task') >= 0)))
  await page.screenshot({ path: path.join(shots, 'write-01-autotask-created.png') })
})
test('admin caps: preview diff then save, config actually changes', async ({ page }) => {
  await login(page, 'admin', process.env.E2E_PW_ADMIN || '', /\/admin\//)
  await openSidebar(page)
  await page.getByRole('tab', { name: '权限变更' }).click()
  const composer = page.locator('#agent-input')
  await composer.fill('关闭企业端的语音输入能力')
  await composer.press('Enter')
  const flow = page.locator('article.caps-flow')
  await expect(flow).toBeVisible({ timeout: 60000 })
  await expect(flow).toContainText('voice_input', { timeout: 60000 })
  const saveBtn = flow.getByRole('button', { name: '确认并保存' })
  await expect(saveBtn).toBeEnabled({ timeout: 30000 })
  await saveBtn.click()
  await expect(flow).toContainText('已保存', { timeout: 60000 })
  console.log('CAPS_SAVED ok')
  await page.screenshot({ path: path.join(shots, 'write-02-caps-saved.png') })
})