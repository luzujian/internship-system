import { test, expect, type Page } from '@playwright/test'
import path from 'node:path'
const shots = path.resolve('./output/agent-real-lifecycle-20260918/shots')
const ACCOUNT = process.env.E2E_AI_ACCOUNT || 's001'
const PASSWORD = process.env.E2E_AI_PASSWORD || '123456'
async function login(page: Page) {
  await page.goto('/login', { waitUntil: 'domcontentloaded' })
  await page.fill("input[placeholder='请输入账号']", ACCOUNT)
  await page.fill("input[placeholder='请输入密码']", PASSWORD)
  await page.getByRole('button', { name: /登\s*录/ }).first().click()
  await page.waitForURL(/\/student\//, { timeout: 45000 })
}
async function openSidebar(page: Page) {
  const entry = page.getByRole('button', { name: 'AI 助手' })
  await expect(entry).toBeVisible({ timeout: 30000 })
  await entry.click()
  await expect(page.locator('#agent-input')).toBeVisible({ timeout: 20000 })
}
async function sendQuestion(page: Page, text: string) {
  const composer = page.locator('#agent-input')
  await composer.fill(text)
  await composer.press('Enter')
  const turn = page.locator('article.agent-turn').last()
  await expect(turn).toBeVisible({ timeout: 30000 })
  return turn
}
test('stop freezes answer', async ({ page }) => {
  await login(page)
  await openSidebar(page)
  const turn = await sendQuestion(page, '请详细介绍我的实习计划每一步该做什么')
  const stopBtn = page.getByRole('button', { name: '停止查询' })
  await expect(stopBtn).toBeVisible({ timeout: 30000 })
  await stopBtn.click()
  await expect(turn.locator('.task-status')).toContainText('已停止', { timeout: 60000 })
  const taskId = await turn.getAttribute('data-task-id')
  const a1 = await turn.locator('.agent-answer').first().innerText().catch(() => '')
  await page.waitForTimeout(6000)
  const a2 = await turn.locator('.agent-answer').first().innerText().catch(() => '')
  expect(a2.length).toBe(a1.length)
  console.log('LIFECYCLE_STOP task=' + taskId + ' frozen_len=' + a1.length)
  await page.screenshot({ path: path.join(shots, 'life-01-stopped.png') })
})
test('requery creates new version', async ({ page }) => {
  const resends: string[] = []
  page.on('request', r => {
    if (r.url().indexOf('/api/agent/tasks/') >= 0 && r.url().indexOf('/resend') >= 0 && r.method() === 'POST') resends.push(r.url())
  })
  await login(page)
  await openSidebar(page)
  const turn = await sendQuestion(page, '我的申请进度怎么样？')
  await expect(turn.locator('.task-status')).toContainText('已完成', { timeout: 150000 })
  const oldId = await turn.getAttribute('data-task-id')
  const requery = turn.getByRole('button', { name: '重新查询' })
  if (await requery.count() > 0) await requery.click()
  else await turn.getByRole('button', { name: '重新生成' }).click()
  await expect(page.locator('article.agent-turn')).toHaveCount(2, { timeout: 150000 })
  const turn2 = page.locator('article.agent-turn').nth(1)
  await expect(turn2.locator('.task-status')).toContainText('已完成', { timeout: 150000 })
  const newId = await turn2.getAttribute('data-task-id')
  expect(newId).not.toBe(oldId)
  expect(resends.length).toBeGreaterThan(0)
  const ans = (await turn2.locator('.agent-answer').first().innerText()).trim()
  expect(ans.length).toBeGreaterThan(10)
  console.log('LIFECYCLE_REQUERY old=' + oldId + ' new=' + newId + ' ans_len=' + ans.length)
  await page.screenshot({ path: path.join(shots, 'life-02-requeried.png') })
})
test('edit resend creates new version', async ({ page }) => {
  await login(page)
  await openSidebar(page)
  const turn = await sendQuestion(page, '我的待办有哪些？')
  await expect(turn.locator('.task-status')).toContainText('已完成', { timeout: 150000 })
  await turn.getByRole('button', { name: '编辑' }).first().click()
  const box = turn.locator('textarea').first()
  await expect(box).toBeVisible({ timeout: 10000 })
  await box.fill('我现在最紧急的待办是哪一件？')
  await turn.getByRole('button', { name: '保存并重新发送' }).click()
  await expect(page.locator('article.agent-turn')).toHaveCount(2, { timeout: 150000 })
  const turn2 = page.locator('article.agent-turn').nth(1)
  await expect(turn2.locator('.task-status')).toContainText('已完成', { timeout: 150000 })
  const pager = turn2.locator('.version-pager')
  await expect(pager).toBeVisible({ timeout: 30000 })
  await expect(pager).toContainText('2')
  const ans = (await turn2.locator('.agent-answer').first().innerText()).trim()
  expect(ans.length).toBeGreaterThan(10)
  console.log('LIFECYCLE_EDIT ans_len=' + ans.length)
  await page.screenshot({ path: path.join(shots, 'life-03-edited.png') })
})
test('refresh recovers same task', async ({ page }) => {
  await login(page)
  await openSidebar(page)
  const q = '我现在还有什么需要完成？'
  const turn = await sendQuestion(page, q)
  const taskId = await turn.getAttribute('data-task-id')
  await page.reload({ waitUntil: 'domcontentloaded' })
  await openSidebar(page)
  const recovered = page.locator('article.agent-turn[data-task-id="' + taskId + '"]')
  await expect(recovered).toBeVisible({ timeout: 60000 })
  await expect(recovered.locator('.task-status')).toContainText(/已完成|已停止/, { timeout: 150000 })
  const count = await page.locator('article.agent-turn', { hasText: q.slice(0, 8) }).count()
  expect(count).toBe(1)
  console.log('LIFECYCLE_REFRESH recovered=' + taskId + ' bubbles=' + count)
  await page.screenshot({ path: path.join(shots, 'life-04-recovered.png') })
})
test('version switch posts nothing', async ({ page }) => {
  const posts: string[] = []
  page.on('request', r => {
    if (r.url().indexOf('/api/agent/tasks') >= 0 && r.method() === 'POST') posts.push(r.method() + ' ' + new URL(r.url()).pathname)
  })
  await login(page)
  await openSidebar(page)
  const turn = await sendQuestion(page, '我的待办有哪些？')
  await expect(turn.locator('.task-status')).toContainText('已完成', { timeout: 150000 })
  const requery = turn.getByRole('button', { name: '重新查询' })
  if (await requery.count() > 0) await requery.click()
  else await turn.getByRole('button', { name: '重新生成' }).click()
  await expect(page.locator('article.agent-turn')).toHaveCount(2, { timeout: 150000 })
  const turn2 = page.locator('article.agent-turn').nth(1)
  await expect(turn2.locator('.task-status')).toContainText('已完成', { timeout: 150000 })
  expect(posts.length).toBeGreaterThan(0)
  posts.length = 0
  await turn2.locator('.version-pager').getByRole('button', { name: '1' }).click()
  await page.waitForTimeout(3000)
  expect(posts.length).toBe(0)
  console.log('LIFECYCLE_SWITCH no_post_on_version_switch=ok')
  await page.screenshot({ path: path.join(shots, 'life-05-switched.png') })
})